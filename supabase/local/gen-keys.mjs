// Generates the anon / service_role JWTs for the LOCAL dev stack (same secret as docker-compose.yml).
//   node supabase/local/gen-keys.mjs            -> prints the keys
//   node supabase/local/gen-keys.mjs --write    -> also writes .env.development.local (git-ignored; overrides .env.local in `next dev`)
import crypto from "node:crypto";
import fs from "node:fs";

const SECRET = "fertiledger-local-dev-secret-0123456789-abcdef";
const URL_ = "http://127.0.0.1:55321";
const b64 = (o) => Buffer.from(JSON.stringify(o)).toString("base64url");
function sign(role) {
  const now = Math.floor(Date.now() / 1000);
  const head = b64({ alg: "HS256", typ: "JWT" });
  const body = b64({ role, iss: "fertiledger-local", iat: now, exp: now + 60 * 60 * 24 * 365 * 5 });
  const sig = crypto.createHmac("sha256", SECRET).update(`${head}.${body}`).digest("base64url");
  return `${head}.${body}.${sig}`;
}
const anon = sign("anon");
const service = sign("service_role");
console.log(JSON.stringify({ url: URL_, anon, service }, null, 2));

if (process.argv.includes("--write")) {
  const env = [
    "# LOCAL DEV STACK ONLY - generated by supabase/local/gen-keys.mjs. Overrides .env.local while running `next dev`.",
    `NEXT_PUBLIC_SUPABASE_URL=${URL_}`,
    `NEXT_PUBLIC_SUPABASE_ANON_KEY=${anon}`,
    `SUPABASE_SECRET_KEY=${service}`,
    'NEXT_PUBLIC_APP_NAME="FertiLedger ERP (local)"',
    "",
  ].join("\n");
  fs.writeFileSync(new URL("../../.env.development.local", import.meta.url), env);
  console.error("wrote .env.development.local");
}
